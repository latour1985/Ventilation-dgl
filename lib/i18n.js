const ContexteLangue = createContext({
  langue: "fr",
  setLangue: () => {},
  t: (texte, valeurs) => remplir(texte, valeurs),
});

// Remplit les {trous} d'une phrase : remplir("{n} tâches", { n: 3 }).
function remplir(texte, valeurs) {
  if (!valeurs) return texte;
  return String(texte).replace(/\{(\w+)\}/g, (tout, cle) => (valeurs[cle] !== undefined && valeurs[cle] !== null ? String(valeurs[cle]) : tout));
}

// `initiale` (2026-10-03, pages envoyées aux clients) : la langue imposée
// par le lien (« ?lang=en » quand la fiche du client est en anglais). Elle
// prime sur le choix mémorisé du navigateur, sans l'écraser.
export function LangueProvider({ children, initiale = null }) {
  const [langue, setLangueEtat] = useState(initiale === "en" ? "en" : "fr");
  // Lecture APRÈS le premier rendu (localStorage n'existe pas au
  // prérendu serveur) — l'écran part en français puis bascule, ce qui
  // est invisible en pratique.
  useEffect(() => {
    if (initiale === "en" || initiale === "fr") return;
    try {
      if (localStorage.getItem(CLE_STOCKAGE) === "en") setLangueEtat("en");
    } catch {
      // stockage indisponible — on reste en français
    }
  }, [initiale]);
  const setLangue = (l) => {
    const propre = l === "en" ? "en" : "fr";
    setLangueEtat(propre);
    try {
      localStorage.setItem(CLE_STOCKAGE, propre);
    } catch {
      // pas grave : le choix vaudra pour la session en cours
    }
  };
  // t("{n} tâches", { n: 3 }) : la phrase ENTIÈRE est la clé (l'anglais
  // peut changer l'ordre des mots), les {trous} sont remplis après.
  const t = (texte, valeurs) => remplir(langue === "en" ? DICO_EN[texte] ?? texte : texte, valeurs);
  return createElement(ContexteLangue.Provider, { value: { langue, setLangue, t } }, children);
}

// Le crochet à utiliser partout : `const { t } = useLangue();`
export function useLangue() {
  return useContext(ContexteLangue);
}
